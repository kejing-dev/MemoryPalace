package io.embodit.memorypalace.platform

import android.content.Context
import android.graphics.Bitmap
import android.graphics.BitmapFactory
import android.graphics.Matrix
import android.media.ExifInterface
import io.embodit.memorypalace.data.MediaGateway
import io.embodit.memorypalace.data.MediaOutcome
import io.embodit.memorypalace.data.PackSource
import io.embodit.memorypalace.domain.Limits
import io.embodit.memorypalace.domain.MediaError
import java.io.File
import java.security.MessageDigest
import kotlin.math.max
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext

/** `assets/packs/` (the content library, generated by tools/packs). */
class AssetPackSource(context: Context) : PackSource {
    private val assets = context.applicationContext.assets

    override fun index(): String? = read("packs/index.json")

    override fun volume(file: String): String? = read("packs/$file")

    private fun read(path: String): String? = runCatching { assets.open(path).use { it.readBytes().toString(Charsets.UTF_8) } }.getOrNull()
}

/**
 * Picked images and models (design `userContent`): copied into `files/palaces/<palace>/media/` under their
 * content hash. Images are read with their EXIF orientation, the long edge shrunk to 1024 px and saved as
 * JPEG (PNG when they have alpha). Models are checked by extension and size only; loading them is the
 * scene's (S37), on the main thread through `Entity.loadSuspend`. All file work runs on the IO dispatcher.
 */
class MediaFiles(context: Context) : MediaGateway {
    private val dir = context.applicationContext.filesDir

    override suspend fun image(src: File, name: String, palaceId: String): MediaOutcome =
        withContext(Dispatchers.IO) {
            val ext = name.substringAfterLast('.', "").lowercase()
            if (ext !in IMAGE_EXT) return@withContext MediaOutcome.Failed(MediaError.FORMAT_IMAGE)
            if (src.length() > Limits.IMAGE_MAX_BYTES) return@withContext MediaOutcome.Failed(MediaError.TOO_BIG_IMAGE)
            val bounds = BitmapFactory.Options().apply { inJustDecodeBounds = true }
            BitmapFactory.decodeFile(src.path, bounds)
            if (bounds.outWidth <= 0) return@withContext MediaOutcome.Failed(MediaError.FORMAT_IMAGE)
            var sample = 1
            while (max(bounds.outWidth, bounds.outHeight) / (sample * 2) >= Limits.IMAGE_EDGE_PX) sample *= 2
            val decoded = BitmapFactory.decodeFile(src.path, BitmapFactory.Options().apply { inSampleSize = sample }) ?: return@withContext MediaOutcome.Failed(MediaError.FORMAT_IMAGE)
            val rotated = orient(decoded, src)
            val edge = max(rotated.width, rotated.height)
            val scaled = edge > Limits.IMAGE_EDGE_PX || sample > 1
            val out =
                if (edge > Limits.IMAGE_EDGE_PX) {
                    val k = Limits.IMAGE_EDGE_PX.toFloat() / edge
                    Bitmap.createScaledBitmap(rotated, (rotated.width * k).toInt().coerceAtLeast(1), (rotated.height * k).toInt().coerceAtLeast(1), true)
                } else rotated
            val png = out.hasAlpha()
            val tmp = File(mediaDir(palaceId), "tmp-" + System.nanoTime())
            tmp.outputStream().use { out.compress(if (png) Bitmap.CompressFormat.PNG else Bitmap.CompressFormat.JPEG, 88, it) }
            val rel = keep(tmp, palaceId, if (png) "png" else "jpg")
            PalaceLog.i("MEDIA image $name -> $rel ${out.width}x${out.height} scaled=$scaled")
            MediaOutcome.Ok(rel, scaled)
        }

    override suspend fun model(src: File, name: String, palaceId: String): MediaOutcome =
        withContext(Dispatchers.IO) {
            val ext = name.substringAfterLast('.', "").lowercase()
            if (ext !in MODEL_EXT) return@withContext MediaOutcome.Failed(MediaError.FORMAT_MODEL)
            if (src.length() > Limits.MODEL_MAX_BYTES) return@withContext MediaOutcome.Failed(MediaError.TOO_BIG_MODEL)
            val tmp = File(mediaDir(palaceId), "tmp-" + System.nanoTime())
            src.copyTo(tmp, overwrite = true)
            val rel = keep(tmp, palaceId, ext)
            PalaceLog.i("MEDIA model $name -> $rel bytes=${src.length()}")
            MediaOutcome.Ok(rel, false)
        }

    override fun absolute(file: String): String = File(dir, file).path

    override fun delete(file: String) {
        runCatching { File(dir, file).delete() }
    }

    private fun mediaDir(palaceId: String): File = File(dir, "palaces/$palaceId/media").also { it.mkdirs() }

    /** Renames [tmp] to its content hash (the same picture twice is one file). */
    private fun keep(tmp: File, palaceId: String, ext: String): String {
        val md = MessageDigest.getInstance("SHA-1")
        tmp.inputStream().use { input ->
            val buf = ByteArray(64 * 1024)
            while (true) {
                val n = input.read(buf)
                if (n < 0) break
                md.update(buf, 0, n)
            }
        }
        val hash = md.digest().joinToString("") { "%02x".format(it) }.take(20)
        val target = File(mediaDir(palaceId), "$hash.$ext")
        if (target.exists()) tmp.delete() else tmp.renameTo(target)
        return "palaces/$palaceId/media/${target.name}"
    }

    private fun orient(b: Bitmap, src: File): Bitmap {
        val o = runCatching { ExifInterface(src.path).getAttributeInt(ExifInterface.TAG_ORIENTATION, ExifInterface.ORIENTATION_NORMAL) }.getOrDefault(ExifInterface.ORIENTATION_NORMAL)
        val m = Matrix()
        when (o) {
            ExifInterface.ORIENTATION_ROTATE_90 -> m.postRotate(90f)
            ExifInterface.ORIENTATION_ROTATE_180 -> m.postRotate(180f)
            ExifInterface.ORIENTATION_ROTATE_270 -> m.postRotate(270f)
            ExifInterface.ORIENTATION_FLIP_HORIZONTAL -> m.preScale(-1f, 1f)
            ExifInterface.ORIENTATION_FLIP_VERTICAL -> m.preScale(1f, -1f)
            else -> return b
        }
        return Bitmap.createBitmap(b, 0, 0, b.width, b.height, m, true)
    }

    companion object {
        val IMAGE_EXT = setOf("png", "jpg", "jpeg", "webp")
        val MODEL_EXT = setOf("glb", "usdz")
    }
}
