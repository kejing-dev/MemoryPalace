package io.embodit.memorypalace.domain

import io.embodit.memorypalace.data.Library
import io.embodit.memorypalace.data.LibraryCodec
import java.io.File
import kotlin.random.Random
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNotEquals
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Assume.assumeTrue
import org.junit.Test

/** v0.3 content library (design `contentLibrary`) and user items (design `userContent`). */
class ContentLibraryTest {

    private val volume =
        """{"id":"demo-1","zh":"示例 · 卷一","en":"Demo · Vol. 1","tree":[
          {"t":"李白","k":[{"t":"《将进酒》","a":"李白","k":[{"f":"君不见黄河之水天上来","b":"奔流到海不复回"}]}]},
          {"f":"6 号","b":"C 碳 Carbon"}]}"""

    @Test
    fun aVolumeBecomesAPalaceWithFixedIds() {
        val (palace, nodes) = LibraryPacks.build(volume, 2)
        assertEquals("lib-demo-1", palace.id)
        assertEquals("lib:demo-1", palace.source)
        val t = PalaceTree(palace.id, nodes)
        assertEquals(2, t.loci.size)
        assertEquals(3, t.depth)
        val poem = t.children(t.loci[0].id).single()
        assertEquals("李白", poem.author)
        assertEquals("lib-demo-1/0/0/0", t.children(poem.id).single().id)
        assertEquals("奔流到海不复回", t.cards.first().back)
        // the same file gives the same ids (progress survives an update)
        assertEquals(nodes.map { it.id }, LibraryPacks.build(volume, 0).second.map { it.id })
    }

    @Test
    fun trainingDecksAreShuffledEachTime() {
        val (p1, deck1) = LibraryPacks.generate(LibraryPacks.CARDS52, "扑克", "Cards", "a", 0, Random(1))!!
        val (_, deck2) = LibraryPacks.generate(LibraryPacks.CARDS52, "扑克", "Cards", "b", 0, Random(2))!!
        val t = PalaceTree(p1.id, deck1)
        assertEquals(13, t.loci.size)
        assertEquals(52, t.cards.size)
        assertEquals(52, t.cards.map { it.back }.toSet().size)
        assertNotEquals(deck1.filter { it.isCard }.map { it.back }, deck2.filter { it.isCard }.map { it.back })
        val (p, digits) = LibraryPacks.generate(LibraryPacks.DIGITS100, "数字", "Digits", "c", 0, Random(3))!!
        val d = PalaceTree(p.id, digits)
        assertEquals(5, d.loci.size)
        assertEquals(25, d.cards.size)
        assertTrue(d.cards.all { it.back.length == 4 && it.back.all(Char::isDigit) })
        assertNull(LibraryPacks.generate("nope", "", "", "x", 0))
    }

    @Test
    fun indexParses() {
        val idx = LibraryPacks.parseIndex("""{"version":1,"collections":[{"id":"pi","category":"numbers","zh":"圆周率","en":"Pi","cards":50,"volumes":[{"id":"pi-1","zh":"π","en":"Pi","file":"pi-1.json","loci":7,"cards":50}]},{"id":"cards52","category":"numbers","zh":"扑克","generated":true,"volumes":[]}]}""")
        assertEquals(listOf("pi", "cards52"), idx.map { it.id })
        assertEquals("pi-1.json", idx[0].volumes.single().file)
        assertTrue(idx[1].generated)
    }

    /** The bundled packs keep the limits (they are generated by tools/packs; the test reads the assets when present). */
    @Test
    fun bundledPacksKeepTheLimits() {
        val dir = listOf(File("src/main/assets/packs"), File("app/src/main/assets/packs")).firstOrNull { it.isDirectory }
        assumeTrue(dir != null && File(dir, "index.json").isFile)
        val index = LibraryPacks.parseIndex(File(dir, "index.json").readText())
        assertTrue(index.size >= 15)
        for (c in index) for (v in c.volumes) {
            val (p, nodes) = LibraryPacks.build(File(dir, v.file).readText(), 0)
            val t = PalaceTree(p.id, nodes)
            assertTrue("${v.id} loci", t.loci.size in 1..Limits.LOCI_PER_PALACE)
            assertTrue("${v.id} cards", t.cards.size in 1..Limits.CARDS_PER_PALACE)
            assertTrue("${v.id} depth", t.depth <= Limits.MAX_DEPTH)
            assertTrue("${v.id} children", t.nodes.all { t.children(it.id).size <= Limits.CHILDREN_PER_NODE } && t.loci.size <= Limits.LOCI_PER_PALACE)
            assertEquals("${v.id} count", v.cards, t.cards.size)
        }
    }

    @Test
    fun userItemsInABundledPalaceSurviveASave() {
        val tang = Presets.nodes(Presets.TANG)
        val du = PalaceTree(Presets.TANG, tang).loci.first { it.title == "杜甫" }
        val added = Node("${du.id}/u1", Presets.TANG, du.id, 9, NodeKind.CARD, front = "箭头模型", back = "背面", srs = Srs(), media = Media(MediaKind.MODEL, "palaces/pack-tang/media/ab.glb", "sample", beside = true, yawDeg = 90f))
        val renamed = du.copy(title = "杜甫的书桌")
        val nodes = Presets.nodes().map { if (it.id == du.id) renamed else it } + added
        val lib = Library(Presets.palaces, nodes, emptyList(), Presets.TANG)
        val (p, n, l) = LibraryCodec.encode(lib)
        val back = LibraryCodec.decode(p, n, l)
        val t = PalaceTree(Presets.TANG, back.nodes)
        assertEquals("杜甫的书桌", t[du.id]?.title)
        val m = t[added.id]?.media
        assertEquals(MediaKind.MODEL, m?.kind)
        assertEquals(90f, m?.yawDeg ?: 0f, 1e-4f)
        assertTrue(m?.beside == true)
        // one copy of each node, the untouched ones still from the bundle
        assertEquals(back.nodes.size, back.nodes.map { it.id }.toSet().size)
        assertEquals(35, t.cards.size)
    }
}
